import re

def clean_math_text(text):
    """Converts raw LaTeX code into clean, student-readable plain text."""
    replacements = [
        (r"\\binom\{([^}]+)\}\{([^}]+)\}", r"C(\1, \2)"),
        (r"\\frac\{([^}]+)\}\{([^}]+)\}", r"(\1 / \2)"),
        (r"\\implies", "=>"),
        (r"\\times", "*"),
        (r"\\cdot", "*"),
        (r"\\pm", "+/-"),
        (r"\\le", "<="),
        (r"\\ge", ">="),
        (r"\\neq", "!="),
        (r"\\alpha", "alpha"),
        (r"\\beta", "beta"),
        (r"\\theta", "theta"),
        (r"\\pi", "pi"),
        (r"\$", ""),           # Remove all $ dollar signs
        (r"\*\*", ""),         # Remove bold markdown asterisks
    ]
    cleaned = text
    for pattern, repl in replacements:
        cleaned = re.sub(pattern, repl, cleaned)
    return cleaned


def generate_pdf(user_name, summary_text):
    pdf = FPDF()
    pdf.set_margins(left=15, top=15, right=15)
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # Header / Title
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(pdf.epw, 10, "DoubtBuster AI - Revision Digest", ln=True, align="C")

    # Metadata
    pdf.set_font("Helvetica", "I", 10)
    pdf.set_text_color(100, 116, 139)
    date_str = datetime.now().strftime("%d %B %Y, %I:%M %p")
    pdf.cell(pdf.epw, 7, f"Student: {user_name}  |  Generated on: {date_str}", ln=True, align="C")
    pdf.ln(3)

    # Divider line
    pdf.set_draw_color(203, 213, 225)
    pdf.set_line_width(0.5)
    curr_y = pdf.get_y()
    pdf.line(15, curr_y, 15 + pdf.epw, curr_y)
    pdf.ln(5)

    # Clean the entire text from LaTeX clutter
    cleaned_summary = clean_math_text(summary_text)

    # Body Content
    pdf.set_text_color(15, 23, 42)
    for raw_line in cleaned_summary.split("\n"):
        line = raw_line.strip()
        if not line or line.startswith("=") or line.startswith("---"):
            continue
        
        pdf.set_x(15)
        # Main section headings
        if any(line.startswith(num) for num in ["1.", "2.", "3.", "4."]):
            pdf.ln(4)
            pdf.set_font("Helvetica", "B", 12)
            safe_text = line.encode("latin-1", "replace").decode("latin-1")
            pdf.multi_cell(pdf.epw, 7, safe_text)
            pdf.set_font("Helvetica", "", 10)
        else:
            safe_text = line.encode("latin-1", "replace").decode("latin-1")
            pdf.multi_cell(pdf.epw, 6, safe_text)

    # Footer
    pdf.ln(6)
    pdf.set_x(15)
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(148, 163, 184)
    pdf.cell(pdf.epw, 8, "Keep learning and revising! Powered by DoubtBuster AI", ln=True, align="C")

    return bytes(pdf.output())


def send_email(to_address, user_name, summary_text):
    try:
        timestamp = datetime.now().strftime("%d %b %Y, %I:%M %p")
        subject = f"⚡ DoubtBuster AI Revision Notes - {user_name} ({timestamp})"
        body = (
            f"Hi {user_name},\n\n"
            f"Here is your study session digest generated on {timestamp}:\n\n"
            f"{summary_text}\n\n"
            f"-----------------------------------------\n"
            f"Never stop learning! 🚀\n"
            f"Generated by DoubtBuster AI"
        )

        message = MIMEText(body, "plain", "utf-8")
        message["Subject"] = subject
        message["From"] = GMAIL_ADDRESS
        message["To"] = to_address

        with smtplib.SMTP_SSL("smtp.gmail.com", 465) as server:
            server.login(GMAIL_ADDRESS, GMAIL_APP_PASSWORD)
            server.send_message(message)
        return True, "Email sent successfully!"
    except Exception as e:
        return False, str(e)


def render_message(message):
    with st.chat_message(message["role"]):
        if message["kind"] == "text":
            st.markdown(message["content"])
        elif message["kind"] == "image":
            st.image(message["content"], use_container_width=True)


def add_message(role, kind, content):
    st.session_state.messages.append({"role": role, "kind": kind, "content": content})
    render_message(st.session_state.messages[-1])


def init_chat_session(subject_focus="General Academic"):
    mode_prompt = f"{SYSTEM_PROMPT}\n\nPrimary Focus Domain for this session: {subject_focus}."
    for model_name in MODELS:
        try:
            chat = gemini_client.chats.create(
                model=model_name,
                config=types.GenerateContentConfig(system_instruction=mode_prompt),
            )
            st.session_state.active_model = model_name
            return chat
        except Exception:
            continue
    st.session_state.active_model = MODELS[0]
    return gemini_client.chats.create(
        model=MODELS[0],
        config=types.GenerateContentConfig(system_instruction=mode_prompt),
    )


def ask_gemini(parts):
    for attempt in range(2):
        try:
            return st.session_state.chat.send_message(parts).text
        except Exception as error:
            err_msg = str(error)
            if "503" in err_msg:
                time.sleep(1.5)
                continue
            break

    fallback_models = [m for m in MODELS if m != st.session_state.get("active_model")]
    for fallback in fallback_models:
        try:
            temp_chat = gemini_client.chats.create(
                model=fallback,
                config=types.GenerateContentConfig(system_instruction=SYSTEM_PROMPT),
            )
            resp = temp_chat.send_message(parts).text
            st.session_state.chat = temp_chat
            st.session_state.active_model = fallback
            return resp
        except Exception:
            continue

    return "Server is temporarily busy. Please try again."


